export const getRelatedStudios = (studio: Studio, limit = 3): Studio[] => {
  return studios
    .filter((s) => s.id !== studio.id && s.category === studio.category)
    .concat(studios.filter((s) => s.id !== studio.id && s.category !== studio.category))
    .slice(0, limit);
};
