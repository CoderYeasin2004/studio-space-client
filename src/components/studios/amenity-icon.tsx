export function AmenityIcon({
  name,
  className,
}: {
  name: string;
  className?: string;
}) {
  const Icon = AMENITY_ICONS[name] ?? SparklesIcon;
  return <Icon className={className} strokeWidth={1.75} aria-hidden />;
}
